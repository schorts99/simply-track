export function translate(language: Language, message: string, values: TranslationValues = {}): string {
  const template = language === "es" && Object.hasOwn(spanish, message) ? spanish[message as keyof typeof spanish] : message;
  return template.replace(/\{(\w+)\}/g, (placeholder, name: string) => Object.hasOwn(values, name) ? String(values[name]) : placeholder);
}

// Adapt existing domain/infrastructure errors at the presentation boundary, without UI dependencies in those layers.
export function translateError(language: Language, message: string): string {
  const translateMessage = (key: string, values?: TranslationValues) => translate(language, key, values);
  const required = /^(Title|Goal name|Scenario name) is required \(maximum (\d+) characters\)\.$/.exec(message);
  if (required) return translateMessage("{label} is required (maximum {max} characters).", { label: translateMessage(required[1]), max: required[2] });
  const offline = /^Offline support could not be enabled: ([\s\S]*)$/.exec(message);
  if (offline) return translateMessage("Offline support could not be enabled: {detail}", { detail: translateError(language, offline[1]) });
  const google = /^Google sign-in (failed|did not complete): ([\s\S]*)$/.exec(message);
  if (google) return translateMessage(`Google sign-in ${google[1]}: {detail}`, { detail: translateMessage(google[2]) });
  const request = /^Google Drive request failed \((\d+)\)\. Your local vault is unchanged\.$/.exec(message);
  if (request) return translateMessage("Google Drive request failed ({status}). Your local vault is unchanged.", { status: request[1] });
  return translateMessage(message);
}
