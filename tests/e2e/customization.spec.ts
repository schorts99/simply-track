import { expect, test, type Page } from "@playwright/test";

async function createVault(page: Page) {
  await page.goto("/");
  await page.getByLabel("Vault password", { exact: true }).fill("a secure customization password");
  await page.getByLabel("Confirm password", { exact: true }).fill("a secure customization password");
  await page.getByRole("button", { name: "Create my private vault" }).click();
  await expect(page.getByRole("heading", { name: "A little clarity. A lot of possibility." })).toBeVisible();
}

test("settings and record dialogs remain interactive through repeated opens, cancel and save", async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await createVault(page);
  const settings = page.getByRole("button", { name: testInfo.project.name === "mobile" ? "Settings" : "Settings & storage", exact: true });
  await settings.click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByRole("heading", { name: "Your space, your settings" })).toBeVisible();
  await dialog.getByRole("button", { name: "Close dialog" }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByLabel("Selected month").fill("2025-08");
  await page.getByRole("button", { name: "Add transaction", exact: true }).click();
  await expect(dialog.getByLabel("Date", { exact: true })).toHaveValue("2025-08-01");
  await dialog.getByLabel("Description", { exact: true }).fill("My functional transaction");
  await dialog.getByLabel("Amount", { exact: true }).fill("17.50");
  await dialog.getByRole("button", { name: "Save changes" }).click();
  await expect(page.getByText("My functional transaction", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: /My functional transaction Food & Dining/ }).click();
  await dialog.getByLabel("Description", { exact: true }).fill("Edited transaction");
  await dialog.getByRole("button", { name: "Save changes" }).click();
  await expect(page.getByText("Edited transaction", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Create a budget", exact: true }).click();
  await dialog.getByLabel("Monthly limit").fill("100");
  await dialog.getByRole("button", { name: "Save changes" }).click();
  await page.getByRole("button", { name: "Set a savings goal", exact: true }).click();
  await dialog.getByLabel("Goal name").fill("A working goal");
  await dialog.getByLabel("Target amount").fill("500");
  await dialog.getByRole("button", { name: "Save changes" }).click();
  await expect(page.getByText("A working goal", { exact: true })).toBeVisible();
  await settings.click();
  await dialog.getByRole("button", { name: "Edit preferences" }).click();
  await expect(dialog.getByRole("heading", { name: "Your preferences" })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(dialog).not.toBeVisible();
  await settings.click();
  await expect(dialog.getByRole("heading", { name: "Your space, your settings" })).toBeVisible();
  await dialog.getByRole("button", { name: "Close dialog" }).click();
  await page.getByRole("button", { name: "Delete Edited transaction", exact: true }).click();
  await dialog.getByRole("button", { name: "Remove record" }).click();
  await expect(page.getByText("Edited transaction", { exact: true })).not.toBeVisible();
  expect(errors).toEqual([]);
});

test("personalization flows into records, budgets, forecasts and encrypted reloads", async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await createVault(page);
  const settingsButton = page.getByRole("button", { name: testInfo.project.name === "mobile" ? "Settings" : "Settings & storage", exact: true });
  const dialog = page.getByRole("dialog");
  const preferences = async () => {
    await settingsButton.click();
    await dialog.getByRole("button", { name: "Edit preferences" }).click();
    await expect(dialog.getByLabel("Your name", { exact: true })).toBeVisible();
  };
  const section = (name: string) => dialog.locator("details").filter({ has: page.locator("summary").getByText(name, { exact: true }) });
  await preferences();
  await dialog.getByLabel("Your name", { exact: true }).fill("Alex");
  await dialog.getByLabel("Workspace name", { exact: true }).fill("Alex's household");
  await dialog.getByRole("combobox", { name: "Currency", exact: true }).selectOption("EUR");
  await dialog.getByLabel("Expected monthly income", { exact: true }).fill("3000");
  await dialog.getByLabel("Expected monthly expenses", { exact: true }).fill("1000");
  await dialog.getByLabel("Opening balance", { exact: true }).fill("500");
  await dialog.getByLabel("Forecast months", { exact: true }).fill("12");
  for (const [name, value] of [["Expense categories", "Pet care"], ["Income categories", "Small business"], ["Payment methods", "Shared account"]]) {
    const catalog = section(name);
    await catalog.locator("summary").click();
    await catalog.getByRole("button", { name: "Add option" }).click();
    await catalog.getByRole("textbox").last().fill(value);
  }
  const shortcuts = section("Quick actions");
  await shortcuts.locator("summary").click();
  while (await shortcuts.getByRole("button", { name: "Remove quick action" }).count()) await shortcuts.getByRole("button", { name: "Remove quick action" }).first().click();
  await shortcuts.getByRole("button", { name: "Add quick action", exact: true }).click();
  await shortcuts.getByLabel("Description", { exact: true }).fill("Pet supplies");
  await shortcuts.getByLabel("Amount", { exact: true }).fill("20");
  await shortcuts.getByRole("combobox", { name: "Category", exact: true }).selectOption({ label: "Pet care" });
  await shortcuts.getByRole("combobox", { name: "Payment method", exact: true }).selectOption({ label: "Shared account" });
  await dialog.getByRole("button", { name: "Save changes" }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole("button", { name: "Pet supplies €20.00", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Pet supplies €20.00", exact: true }).click();
  await expect(page.getByText("Pet supplies", { exact: true }).last()).toBeVisible();
  await page.getByRole("button", { name: /Pet supplies Pet care/ }).click();
  await expect(dialog.getByRole("combobox", { name: "Payment method", exact: true }).locator("option:checked")).toHaveText("Shared account");
  await dialog.getByRole("button", { name: "Close dialog" }).click();
  await page.getByRole("button", { name: "Add transaction", exact: true }).click();
  await dialog.getByRole("button", { name: "Income", exact: true }).click();
  await dialog.getByLabel("Description", { exact: true }).fill("My business income");
  await dialog.getByLabel("Amount", { exact: true }).fill("100");
  await dialog.getByRole("combobox", { name: "Category", exact: true }).selectOption({ label: "Small business" });
  await dialog.getByRole("button", { name: "Save changes" }).click();
  await page.getByRole("button", { name: "Create a budget", exact: true }).click();
  await dialog.getByRole("combobox", { name: "Expense category", exact: true }).selectOption({ label: "Pet care" });
  await dialog.getByLabel("Monthly limit", { exact: true }).fill("100");
  await dialog.getByRole("button", { name: "Save changes" }).click();
  await preferences();
  const expenses = section("Expense categories");
  await expenses.locator("summary").click();
  await expenses.getByRole("textbox").last().fill("Animal care");
  const shortcutsAgain = section("Quick actions");
  await shortcutsAgain.locator("summary").click();
  await shortcutsAgain.getByRole("button", { name: "Remove quick action" }).click();
  await expenses.getByRole("checkbox", { name: "Active Animal care", exact: true }).uncheck();
  await dialog.getByRole("button", { name: "Save changes" }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.locator(".quick-card")).toHaveCount(0);
  await expect(page.getByRole("button", { name: /Pet supplies Animal care/ })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("button", { name: /Pet supplies Animal care/ })).toBeVisible();
  await page.getByRole("button", { name: "Add transaction", exact: true }).click();
  await expect(dialog.getByRole("combobox", { name: "Category", exact: true }).getByRole("option", { name: "Animal care" })).toHaveCount(0);
  await dialog.getByRole("button", { name: "Close dialog" }).click();
  await page.getByRole("button", { name: /Pet supplies Animal care/ }).click();
  await expect(dialog.getByRole("combobox", { name: "Category", exact: true }).locator("option:checked")).toHaveText("Animal care");
  await dialog.getByLabel("Amount", { exact: true }).fill("25");
  await dialog.getByRole("button", { name: "Save changes" }).click();
  const nav = page.getByRole("navigation", { name: testInfo.project.name === "mobile" ? "Mobile navigation" : "Main navigation" });
  await nav.getByRole("button", { name: testInfo.project.name === "mobile" ? "Forecast" : "Cashflow forecast", exact: true }).click();
  await expect(page.getByRole("row")).toHaveCount(13);
  await expect(page.getByRole("row").nth(1)).toContainText("€2,575.00");
  await settingsButton.click();
  await expect(dialog.getByRole("heading", { name: "Alex", exact: true })).toBeVisible();
  await expect(dialog.getByText("Alex's household", { exact: true })).toBeVisible();
  await dialog.getByRole("combobox", { name: "Language" }).selectOption("es");
  await expect(dialog.getByRole("heading", { name: "Alex", exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Editar preferencias" }).click();
  await expect(dialog.getByLabel("Tu nombre", { exact: true })).toHaveValue("Alex");
  await expect(dialog.getByLabel("Meses de proyección", { exact: true })).toHaveValue("12");
  await page.setViewportSize({ width: 320, height: 740 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await dialog.getByRole("button", { name: "Cerrar ventana" }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
