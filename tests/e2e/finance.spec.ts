import { expect, test } from "@playwright/test";

test("encrypted finance workflows persist, lock, import and work offline", async ({ page, context }, testInfo) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  await page.getByLabel("Vault password", { exact: true }).fill("a safe test password 123");
  await page.getByLabel("Confirm password", { exact: true }).fill("a safe test password 123");
  await page.getByRole("button", { name: "Create my private vault" }).click();
  await expect(page.getByRole("heading", { name: "A little clarity. A lot of possibility." })).toBeVisible();
  await page.getByRole("button", { name: "Add transaction", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByRole("button", { name: "Income", exact: true }).click();
  await dialog.getByLabel("Description", { exact: true }).fill("Monthly salary");
  await dialog.getByLabel("Amount", { exact: true }).fill("4000");
  await dialog.getByRole("button", { name: "Save changes" }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole("button", { name: "Add transaction", exact: true }).click();
  await dialog.getByLabel("Description", { exact: true }).fill("Market run");
  await dialog.getByLabel("Amount", { exact: true }).fill("55.29");
  await dialog.getByRole("combobox", { name: "Category", exact: true }).selectOption("Groceries");
  await dialog.getByRole("button", { name: "Save changes" }).click();
  await expect(page.getByText("Market run", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Create a budget", exact: true }).click();
  await dialog.getByRole("combobox", { name: "Expense category", exact: true }).selectOption("Groceries");
  await dialog.getByLabel("Monthly limit").fill("300");
  await dialog.getByRole("button", { name: "Save changes" }).click();
  await page.getByRole("button", { name: "Set a savings goal", exact: true }).click();
  await dialog.getByLabel("Goal name").fill("New adventure");
  await dialog.getByLabel("Target amount").fill("2000");
  await dialog.getByLabel("Already set aside").fill("250");
  await dialog.getByRole("button", { name: "Save changes" }).click();
  await expect(page.getByText("New adventure", { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath("overview.png"), fullPage: true });
  await page.reload();
  await expect(page.getByText("Market run", { exact: true })).toBeVisible();
  // A second tab cannot acquire write access to the same device file.
  const second = await context.newPage();
  await second.goto("/");
  await expect(second.getByRole("alert").filter({ hasText: "another tab" })).toBeVisible();
  await second.close();
  const settings = page.getByRole("button", { name: testInfo.project.name === "mobile" ? "Settings" : "Settings & storage", exact: true });
  await settings.click();
  const backup = page.waitForEvent("download");
  await dialog.getByRole("button", { name: "Export backup" }).click();
  const downloaded = await backup;
  const backupPath = await downloaded.path();
  expect(backupPath).toBeTruthy();
  await dialog.getByRole("button", { name: "Lock vault & log out" }).click();
  await expect(page.getByRole("heading", { name: "Welcome back." })).toBeVisible();
  await page.getByLabel("Vault password", { exact: true }).fill("incorrect password");
  await page.getByRole("button", { name: "Unlock my vault" }).click();
  await expect(page.getByRole("alert").filter({ hasText: "incorrect" })).toBeVisible();
  await page.getByLabel("Vault password", { exact: true }).fill("a safe test password 123");
  await page.getByRole("button", { name: "Unlock my vault" }).click();
  await expect(page.getByText("Market run", { exact: true })).toBeVisible();
  await settings.click();
  await dialog.getByRole("button", { name: "Import backup", exact: true }).click();
  await page.getByLabel("Import encrypted vault file").setInputFiles(backupPath!);
  const replace = page.getByRole("dialog", { name: "Replace this device's vault?" });
  await replace.getByLabel("Backup password").fill("a safe test password 123");
  await replace.getByRole("checkbox").check();
  await replace.getByRole("button", { name: "Unlock & import vault" }).click();
  await expect(replace).not.toBeVisible();
  await expect(page.getByText("Market run", { exact: true })).toBeVisible();
  await page.evaluate(async () => {
    await navigator.serviceWorker.ready;
    if (!navigator.serviceWorker.controller) await new Promise<void>((resolve) => navigator.serviceWorker.addEventListener("controllerchange", () => resolve(), { once: true }));
  });
  await context.setOffline(true);
  await page.reload();
  await expect(page.getByText("Market run", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Add transaction", exact: true }).click();
  await page.getByRole("dialog").getByLabel("Description", { exact: true }).fill("Offline purchase");
  await page.getByRole("dialog").getByLabel("Amount", { exact: true }).fill("8.50");
  await page.getByRole("dialog").getByRole("button", { name: "Save changes" }).click();
  await expect(page.getByText("Offline purchase", { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText("Offline purchase", { exact: true })).toBeVisible();
  await context.setOffline(false);
  expect(errors).toEqual([]);
});

test("planning, scenarios, edits and deletion stay consistent across responsive views", async ({ page }, testInfo) => {
  await page.goto("/");
  await page.getByLabel("Vault password", { exact: true }).fill("another secure test password");
  await page.getByLabel("Confirm password", { exact: true }).fill("another secure test password");
  await page.getByRole("button", { name: "Create my private vault" }).click();
  await page.getByRole("button", { name: "Coffee $5.25", exact: true }).click();
  await page.getByRole("button", { name: "Coffee Food & Dining", exact: false }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Description", { exact: true }).fill("Coffee with a friend");
  await dialog.getByLabel("Amount", { exact: true }).fill("10.50");
  await dialog.getByRole("button", { name: "Save changes" }).click();
  const nav = page.getByRole("navigation", { name: testInfo.project.name === "mobile" ? "Mobile navigation" : "Main navigation" });
  await nav.getByRole("button", { name: testInfo.project.name === "mobile" ? "Activity" : "Transactions", exact: true }).click();
  await page.getByRole("searchbox", { name: "Search transactions" }).fill("with a friend");
  await expect(page.getByText("Coffee with a friend", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Delete Coffee with a friend", exact: true }).click();
  await dialog.getByRole("button", { name: "Remove record", exact: true }).click();
  await expect(page.getByText("Coffee with a friend", { exact: true })).not.toBeVisible();
  await nav.getByRole("button", { name: testInfo.project.name === "mobile" ? "What if" : "What-if scenarios", exact: true }).click();
  await page.getByRole("button", { name: "Explore a scenario", exact: true }).click();
  await dialog.getByLabel("Scenario name", { exact: true }).fill("A small raise");
  await dialog.getByLabel("Monthly income change (+ or -)", { exact: true }).fill("100");
  await dialog.getByRole("button", { name: "Save changes" }).click();
  await expect(page.getByRole("heading", { name: "A small raise", exact: true })).toBeVisible();
  await expect(page.getByText("Six-month balance: $600.00", { exact: true })).toBeVisible();
  await nav.getByRole("button", { name: testInfo.project.name === "mobile" ? "Forecast" : "Cashflow forecast", exact: true }).click();
  await expect(page.getByRole("table")).toBeVisible();
  await expect(page.getByRole("row")).toHaveCount(7);
  await page.setViewportSize({ width: 320, height: 740 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 820, height: 1180 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
